"""CLI to generate a standalone HTML report from validated synthetic session data."""
import argparse
import html
from pathlib import Path
from .analytics import load_sessions, compute_metrics, DataQualityError

def render_dashboard(metrics):
    cards = [
        ("Total sessions", f'{metrics["total_sessions"]:,}'),
        ("Unique players", f'{metrics["unique_players"]:,}'),
        ("Completion rate", f'{metrics["completion_rate"]:.1f}%'),
        ("Repeat-player rate", f'{metrics["repeat_player_rate"]:.1f}%'),
        ("Average score", f'{metrics["avg_score"]:.1f}'),
        ("Revenue", f'${metrics["total_revenue"]:,.2f}'),
    ]
    kpis = "".join(f'<div class="kpi"><span>{html.escape(label)}</span><strong>{value}</strong></div>' for label,value in cards)
    max_sessions = max(x["sessions"] for x in metrics["modes"])
    mode_bars = "".join(
        f'<div class="bar-row"><div class="bar-label"><b>{html.escape(x["name"])}</b><span>{x["sessions"]} sessions · {x["completion_rate"]}% completed</span></div>'
        f'<div class="track"><div class="fill" style="width:{100*x["sessions"]/max_sessions:.0f}%"></div></div></div>'
        for x in metrics["modes"])
    max_players = max(x["players"] for x in metrics["daily_players"])
    daily_bars = "".join(
        f'<div class="daily" title="{x["date"]}: {x["players"]} players"><div class="daily-bar" style="height:{max(10, 100*x["players"]/max_players):.0f}%"></div><small>{html.escape(x["date"][5:])}</small></div>'
        for x in metrics["daily_players"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Capstone Analytics | QA Dashboard</title><style>
*{{box-sizing:border-box}}body{{margin:0;background:#f3f6fb;color:#162339;font-family:Arial,Helvetica,sans-serif}}main{{max-width:1100px;margin:35px auto;padding:0 24px}}
header{{background:linear-gradient(100deg,#15233c,#2d4569);color:#fff;border-radius:20px;padding:28px 34px;box-shadow:0 12px 35px #192a4330}}
.eyebrow{{font-size:12px;letter-spacing:2px;text-transform:uppercase;color:#94eadc;font-weight:700}}h1{{font-size:32px;margin:9px 0 5px;letter-spacing:-.8px}}header p{{color:#d7e6f8;font-size:14px;margin:0}}.pill{{display:inline-block;background:#126e66;color:#baf8e7;border:1px solid #4fada0;padding:7px 11px;border-radius:30px;font-size:12px;margin-top:16px}}
.kpis{{display:grid;grid-template-columns:repeat(3,1fr);gap:16px;margin:23px 0}}.kpi,.panel{{background:white;border-radius:14px;padding:22px;box-shadow:0 4px 13px #28405b12;border:1px solid #e7edf5}}
.kpi span{{color:#63758b;font-size:16px;display:block}}.kpi strong{{font-size:29px;display:block;margin-top:9px;letter-spacing:-.8px}}.panels{{display:grid;grid-template-columns:1.1fr .9fr;gap:18px}}
h2{{font-size:17px;margin:0 0 6px}}.sub{{color:#7a8a9d;font-size:15px;margin:0 0 22px}}.bar-row{{margin:17px 0}}.bar-label{{display:flex;justify-content:space-between;font-size:16px;gap:8px;margin-bottom:8px;color:#657891}}.bar-label b{{color:#24344d}}.track{{height:12px;border-radius:18px;background:#edf2f8;overflow:hidden}}.fill{{height:100%;background:linear-gradient(90deg,#1d8e83,#5cc9ad);border-radius:18px}}.daily-wrap{{display:flex;gap:12px;height:175px;align-items:flex-end;margin-top:10px}}.daily{{height:100%;flex:1;display:flex;flex-direction:column;justify-content:flex-end;align-items:center;gap:8px}}.daily-bar{{width:100%;max-width:45px;background:linear-gradient(#829fe8,#4564b0);border-radius:7px 7px 0 0}}small{{color:#75849b;font-size:11px}}footer{{font-size:14px;color:#657992;margin:21px 0}}@media(max-width:650px){{.kpis{{grid-template-columns:repeat(2,1fr)}}.panels{{grid-template-columns:1fr}}}} </style></head>
<body><main><header><div class="eyebrow">Original learning project · CI/CD + Docker</div><h1>Capstone Analytics Quality Dashboard</h1>
<p>Synthetic gameplay data • validated before reporting • no private data</p><div class="pill">✓ Quality checks completed successfully</div></header>
<section class="kpis">{kpis}</section><section class="panels"><div class="panel"><h2>Game mode breakdown</h2><p class="sub">Sessions per mode; labels show completion percentage.</p>{mode_bars}</div><div class="panel"><h2>Daily active players</h2><p class="sub">Distinct players by day in sample dataset.</p><div class="daily-wrap">{daily_bars}</div></div></section><footer>Generated by src/app.py after validating rows for missing IDs, duplicates, invalid completion values, and negative metrics.</footer></main></body></html>"""

def main():
    parser = argparse.ArgumentParser(description="Validate capstone session data and build a standalone dashboard")
    parser.add_argument("--input", default="data/synthetic_sessions.csv")
    parser.add_argument("--output", default="output/dashboard.html")
    args = parser.parse_args()
    try:
        rows = load_sessions(args.input)
        metrics = compute_metrics(rows)
    except (DataQualityError, FileNotFoundError) as exc:
        parser.exit(2, f"DATA QUALITY FAILURE: {exc}\n")
    output=Path(args.output); output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(render_dashboard(metrics),encoding="utf-8")
    print(f"DATA QUALITY PASS: {metrics['total_sessions']} sessions validated")
    print(f"DASHBOARD GENERATED: {output}")

if __name__ == "__main__":
    main()
